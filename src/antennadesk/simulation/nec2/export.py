"""Render a portable NEC-2 deck with AntennaDesk provenance comments."""

from __future__ import annotations

from dataclasses import dataclass

from ...domain.antennas.antenna import AntennaModel
from ...domain.environment.ground import GroundKind
from ...domain.simulation.spec import SimulationSpec
from .input_writer import write_nec2_input


@dataclass(frozen=True, slots=True)
class NecDeckExportMetadata:
    """Project and tool provenance kept outside the canonical model."""

    project_name: str
    design_name: str
    antenna_type: str
    app_version: str
    solver_name: str | None = None
    solver_version: str | None = None


def _comment(value: str, limit: int = 90) -> str:
    cleaned = value.encode("ascii", errors="replace").decode("ascii")
    cleaned = cleaned.replace("\r", " ").replace("\n", " ").strip()
    return cleaned[:limit]


def _frequency_text(spec: SimulationSpec) -> str:
    plan = spec.frequency_plan
    if plan.is_single:
        return f"{plan.start_hz / 1_000_000.0:.6f} MHz, single frequency"
    return (
        f"{plan.start_hz / 1_000_000.0:.6f}-{plan.stop_hz / 1_000_000.0:.6f} MHz, "
        f"{plan.count} points, step {plan.step_hz / 1_000_000.0:.6f} MHz"
    )


def _ground_text(model: AntennaModel) -> str:
    ground = model.environment.ground
    if ground.kind is GroundKind.FREE_SPACE:
        return "free space"
    if ground.kind is GroundKind.PERFECT:
        return "perfect ground"
    permittivity = ground.relative_permittivity
    conductivity = ground.conductivity_s_per_m
    if permittivity is None or conductivity is None:
        raise ValueError("finite ground requires permittivity and conductivity")
    return f"finite ground, epsilon_r={permittivity:g}, sigma={conductivity:g} S/m"


def _segmentation_text(spec: SimulationSpec) -> str:
    policy = spec.segmentation
    parts = [
        f"target {policy.target_segment_length_wavelengths:g} wavelength",
        f"min {policy.min_segments_per_wire}",
        f"max {policy.max_segments_per_wire}",
    ]
    if policy.segments_per_wire is not None:
        parts.append(f"{policy.segments_per_wire} segments per wire")
    if policy.wire_segments:
        parts.append(f"{len(policy.wire_segments)} explicit wire overrides")
    return ", ".join(parts)


def _solver_text(metadata: NecDeckExportMetadata) -> str:
    if metadata.solver_name is None:
        return "not selected"
    if metadata.solver_version is None:
        return metadata.solver_name
    return f"{metadata.solver_name} {metadata.solver_version}"


def render_nec_deck(
    model: AntennaModel,
    spec: SimulationSpec,
    metadata: NecDeckExportMetadata,
) -> str:
    """Return a deterministic NEC-2 deck with a provenance header.

    The body is generated by the same writer used for simulation. The header
    contains only project, design, plan, ground, segmentation, and tool
    versions; it never includes solver output or private executable paths.
    """

    deck = write_nec2_input(model, spec)
    header = [
        "CM AntennaDesk NEC-2 export",
        f"CM Project: {_comment(metadata.project_name)}",
        f"CM Design: {_comment(metadata.design_name)}",
        f"CM Antenna type: {_comment(metadata.antenna_type)}",
        f"CM Application: AntennaDesk {_comment(metadata.app_version)}",
        f"CM Solver: {_comment(_solver_text(metadata))}",
        f"CM Frequency plan: {_comment(_frequency_text(spec))}",
        f"CM Reference impedance: {spec.reference_impedance_ohm:g} ohm",
        f"CM Ground: {_comment(_ground_text(model))}",
        f"CM Segmentation: {_comment(_segmentation_text(spec))}",
    ]
    if spec.feed_transformer_ratio != 1.0:
        header.append(f"CM Feed transformer: {spec.feed_transformer_ratio:g}:1")
    if spec.feed_line is not None:
        header.append(
            "CM Feed line: "
            f"{spec.feed_line.characteristic_impedance_ohm:g} ohm, "
            f"{spec.feed_line.length_m:g} m, "
            f"vf={spec.feed_line.velocity_factor:g}; post-processed, not in this deck"
        )
    if spec.matching_network is not None:
        header.append("CM Matching network: post-processed, not in this deck")
    deck_lines = deck.text.splitlines()
    try:
        ce_index = deck_lines.index("CE")
    except ValueError:
        ce_index = 0
    return "\n".join([*header, *deck_lines[ce_index:], ""])
